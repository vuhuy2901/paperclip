"""Role output contracts used by the worker and the handoff manifest.

The files are real persisted artifacts even when the local deterministic runner
is selected.  Their contents are explicitly labelled as deterministic output;
they must not be presented as evidence of a model execution.
"""

from pathlib import PurePosixPath

ROLE_ARTIFACTS: dict[str, tuple[str, ...]] = {
    "project-manager": ("prd.md", "acceptance.json", "task-graph.json"),
    "architect": ("architecture.md", "impact-map.json", "openapi.yaml", "migration-plan.md", "design-system/MASTER.md", "user-flows.md", "wireframe.html", "states.json"),
    "backend-developer": ("handoff.json", "test-report.json", "diff.patch"),
    "frontend-developer": ("handoff.json", "screenshot-manifest.json", "diff.patch"),
    "code-reviewer": ("review.json",),
    "tester": ("junit.json", "bugs.json", "test-report.json"),
    "devops": ("deployment-report.json", "smoke-report.json"),
}


def required_artifacts(role: str) -> list[str]:
    try:
        return list(ROLE_ARTIFACTS[role])
    except KeyError as exc:
        raise ValueError(f"unknown role: {role}") from exc


def _json_payload(role: str, task: str, relative_path: str) -> bytes:
    import json

    payload = {
        "schema_version": "1",
        "role": role,
        "artifact": relative_path,
        "status": "completed",
        "mode": "deterministic-fixture",
        "evidence_status": "not_model_execution",
        "task": task,
        "notes": "Generated by the local deterministic runner; replace with trusted runner output for acceptance.",
    }
    return json.dumps(payload, indent=2, ensure_ascii=False).encode("utf-8")


def render_artifact(role: str, task: str, relative_path: str) -> bytes:
    """Render a deterministic, clearly labelled role handoff artifact."""

    path = PurePosixPath(relative_path)
    if path.suffix == ".json":
        return _json_payload(role, task, relative_path)
    if path.suffix in {".md", ".patch", ".yaml"}:
        title = path.stem.replace("-", " ").replace("_", " ").title()
        if path.suffix == ".patch":
            return (
                f"# Deterministic handoff patch ({role})\n\n"
                f"# artifact: {relative_path}\n"
                "# mode: deterministic-fixture; no product source was changed\n"
                f"# task: {task}\n"
            ).encode("utf-8")
        if path.suffix == ".yaml":
            return (
                "# Deterministic contract placeholder; verify against the candidate repository.\n"
                f"role: {role}\nartifact: {relative_path}\nmode: deterministic-fixture\n"
            ).encode("utf-8")
        return (
            f"# {title}\n\n"
            f"- Role: `{role}`\n"
            "- Status: `completed`\n"
            "- Mode: `deterministic-fixture`\n"
            "- Model execution evidence: unavailable\n"
            f"- Task: {task}\n"
        ).encode("utf-8")
    if path.suffix == ".html":
        return (
            "<!doctype html><html><head><meta charset='utf-8'><title>Deterministic wireframe</title></head>"
            f"<body data-role='{role}' data-mode='deterministic-fixture'><main><h1>Wireframe handoff</h1>"
            f"<p>{task}</p><p>Deterministic fixture; not a rendered product review.</p></main></body></html>"
        ).encode("utf-8")
    raise ValueError(f"unsupported artifact extension: {relative_path}")
